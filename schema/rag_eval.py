import time
import uuid
from enum import Enum
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field, field_validator


class RAGMetricType(str, Enum):
    FAITHFULNESS = "faithfulness"
    ANSWER_RELEVANCY = "answer_relevancy"
    CONTEXTUAL_PRECISION = "contextual_precision"
    CONTEXTUAL_RECALL = "contextual_recall"


class LLMTestCase(BaseModel):
    """Represents a single LLM/RAG evaluation test case."""
    test_id: str = Field(default_factory=lambda: f"case_{uuid.uuid4().hex[:6]}")
    input: str = Field(description="The incoming user query or prompt")
    actual_output: str = Field(description="The response generated by the RAG pipeline/LLM")
    expected_output: Optional[str] = Field(default=None, description="Ground truth answer (required for recall)")
    retrieval_context: List[str] = Field(default_factory=list, description="List of retrieved context chunks")
    tags: List[str] = Field(default_factory=list, description="Categorization tags (e.g. out_of_scope, prompt_injection)")


class RAGMetricScore(BaseModel):
    """Result score emitted for a single metric evaluation."""
    metric_name: RAGMetricType
    score: float = Field(ge=0.0, le=1.0, description="Normalized score between 0.0 and 1.0")
    threshold: float = Field(ge=0.0, le=1.0, description="Pass/fail threshold score tau")
    passed: bool = Field(description="Whether score meets or exceeds threshold")
    reasoning: str = Field(description="Explanation or critique from the evaluation judge")


class SyntheticGoldenItem(BaseModel):
    """A synthesized ground-truth Q&A pair generated from raw documentation."""
    id: str = Field(default_factory=lambda: f"synth_{uuid.uuid4().hex[:6]}")
    input: str = Field(description="Synthesized query string")
    expected_output: str = Field(description="Ground truth response derived strictly from context")
    context: List[str] = Field(description="Source documentation chunk(s) supporting the question")
    evolution_type: str = Field(default="simple", description="simple, multihop, or conditional")


class RAGEvalReport(BaseModel):
    """Aggregated evaluation report for a complete test suite run."""
    report_id: str = Field(default_factory=lambda: f"rag_report_{uuid.uuid4().hex[:8]}")
    timestamp: str = Field(default_factory=lambda: time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))
    target_provider: str = Field(default="ollama", description="ollama or openai")
    model_name: str = Field(default="llama3.2:latest")
    passed: bool = Field(description="Overall test suite pass status")
    total_cases: int = 0
    passed_cases: int = 0
    failed_cases: int = 0
    metrics_summary: Dict[str, float] = Field(default_factory=dict)
    case_results: List[Dict[str, Any]] = Field(default_factory=list)
